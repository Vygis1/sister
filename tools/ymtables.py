"""Generate the YM2612's two lookup tables.

    python tools/ymtables.py rtl/ym_tables.vh

The chip does its arithmetic in the LOGARITHMIC domain, which is the single
thing to understand about it. A sine lookup does not return a sine; it returns
how many decibels down from full scale that point of a sine is. The envelope is
also an attenuation in decibels. So modulating amplitude is an ADD, and the only
conversion back to a linear number happens once, at the very end.

That is why there are two tables and not one:

    logsin[i]  -log2(sin((i + 0.5) * pi / 512)) * 256, for a quarter of a sine
    exp[i]     (2^(i / 256) - 1) * 1024, the way back

Both are computed from those definitions rather than transcribed from anywhere,
so they are right by construction -- which matters, because a table that is one
entry out sounds almost correct and is impossible to eyeball.

Only a quarter of the sine is stored. The other three quarters are the same
numbers read backwards and negated, which is what the operator does with the top
two bits of its phase.
"""
import sys
import os
import math


def logsin():
    """A quarter period, as attenuation. The +0.5 matters: sampling at the
    midpoint of each step avoids sin(0), which has no logarithm."""
    out = []
    for i in range(256):
        v = math.sin((i + 0.5) * math.pi / 512.0)
        out.append(int(round(-math.log(v, 2) * 256.0)))
    return out


def exptab():
    """The way back out of the logarithmic domain. The stored value is the
    fractional part only; the operator puts the leading one back, which is what
    the | 0x400 in every implementation of this chip is doing."""
    return [int(round((2.0 ** (i / 256.0) - 1.0) * 1024.0)) for i in range(256)]


def emit(f, name, values, width):
    f.write('\t// %d entries, %d bits each.\n' % (len(values), width))
    f.write('\tinitial begin\n')
    for i, v in enumerate(values):
        assert 0 <= v < (1 << width), 'entry %d does not fit: %d' % (i, v)
        f.write("\t\t%s[%d] = %d'd%d;\n" % (name, i, width, v))
    f.write('\tend\n')


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else 'rtl/ym_tables.vh'
    ls = logsin()
    ex = exptab()

    os.makedirs(os.path.dirname(out) or '.', exist_ok=True)
    with open(out, 'w') as f:
        f.write('// Generated by tools/ymtables.py -- do not edit.\n')
        f.write('//\n')
        f.write('// logsin: -log2(sin((i + 0.5) * pi / 512)) * 256, a quarter period\n')
        f.write('// ymexp:  (2^(i/256) - 1) * 1024, the way back to a linear number\n')
        f.write('//\n')
        f.write('// Both are attenuations in a logarithmic domain, which is why the\n')
        f.write('// operator adds its envelope to its sine instead of multiplying.\n')
        f.write('\n')
        emit(f, 'logsin', ls, 12)
        f.write('\n')
        emit(f, 'ymexp', ex, 11)

    print('%s: logsin %d..%d, exp %d..%d'
          % (out, min(ls), max(ls), min(ex), max(ex)))


if __name__ == '__main__':
    main()
