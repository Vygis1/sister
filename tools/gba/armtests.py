"""Converts the SingleStepTests ARM7TDMI suite into one flat hex stream for sim/tb_arm7.v.
    git clone --depth 1 --filter=blob:none --sparse https://github.com/SingleStepTests/ARM7TDMI build/dl/arm7tests
    (cd build/dl/arm7tests && git sparse-checkout set v1)
    python tools/gba/armtests.py                       -> build/arm7tests.hex (every file)
    python tools/gba/armtests.py arm_b_bl thumb_bx     -> only those files
    python tools/gba/armtests.py -n 2000 ...           -> the first 2000 tests of each file

The suite's state is the user bank R0-R15 plus the banked sets (fiq R8-R14, svc/abt/irq/und
R13-R14), CPSR, the five SPSRs (fiq svc abt irq und) and the two pipeline words [decode,
fetch]; R15 is the address of the test's opcode + 8 (ARM) or + 4 (Thumb). The tests were
generated by NanoBoyAdvance: the core runs the one instruction and must then hold the final
state, and its data reads and writes must come in the order and at the addresses the list
gives (instruction fetches: the word at the opcode's address is the opcode, any other address
reads as its own value, low 16 bits for Thumb).

One record, all words in hex:
    opcode base                                        (base: the opcode's address)
    39 words: R0-15 fiq8-14 svc13-14 abt13-14 irq13-14 und13-14 cpsr spsr*5 pipe0 pipe1   initial
    39 words                                                                              final
    n (kind size addr data)*n                          the data reads (1) and writes (2), in order
"""
import glob
import os
import sys
from struct import unpack_from

SRC = os.path.join('build', 'dl', 'arm7tests', 'v1')
OUT = os.path.join('build', 'arm7tests.hex')


def state(buf, p):
    sz = unpack_from('i', buf, p)[0]
    v = unpack_from('I' * 40, buf, p + 8)
    return sz, v[:39]


def test(buf, p):
    full = unpack_from('i', buf, p)[0]
    p += 4
    sz, ini = state(buf, p); p += sz
    sz, fin = state(buf, p); p += sz
    sz, mn, n = unpack_from('iii', buf, p)
    tr = [unpack_from('<IIIIII', buf, p + 12 + k * 24) for k in range(n)]
    p += sz
    op, base = unpack_from('II', buf, p + 8)
    return full, ini, fin, tr, op, base


def unpredictable(op, thumb):
    """the cases the architecture leaves undefined, which no two parts need agree on: the PC
    as a written-back base (LDR/STR with W or post-indexing, LDM/STM with W), the PC as the
    base of a halfword transfer with write-back"""
    if thumb:
        return False
    if (op >> 26) & 3 == 1:                       # LDR/STR
        rn = (op >> 16) & 15; p = (op >> 24) & 1; w = (op >> 21) & 1
        return rn == 15 and (w or not p)
    if (op >> 25) & 7 == 4:                       # LDM/STM
        return (op >> 16) & 15 == 15
    if (op >> 25) & 7 == 0 and (op >> 4) & 1 and not (op >> 7) & 1 and (op >> 4) & 0xFFFFFF != 0x12FFF1:   # data processing shifted by a register (not BX): Rs = PC
        return (op >> 8) & 15 == 15
    if (op >> 24) & 15 == 0 and (op >> 4) & 15 == 9:   # multiplies: the PC anywhere
        return (op >> 16) & 15 == 15 or (op >> 12) & 15 == 15 or (op >> 8) & 15 == 15 or op & 15 == 15
    if (op >> 23) & 31 == 2 and (op >> 20) & 3 == 0 and (op >> 4) & 255 == 9:   # SWP with the PC as the base
        return (op >> 16) & 15 == 15
    if (op >> 23) & 31 == 2 and (op >> 20) & 3 == 0 and (op >> 16) & 15 == 15 and (op >> 4) & 255 != 9:   # MRS into the PC
        return (op >> 12) & 15 == 15
    if (op >> 25) & 7 == 0 and (op >> 7) & 1 and (op >> 4) & 1 and (op >> 5) & 3:   # halfword forms
        rn = (op >> 16) & 15; p = (op >> 24) & 1; w = (op >> 21) & 1
        return rn == 15 and (w or not p)
    return False


def main():
    args = sys.argv[1:]
    limit = None
    if args and args[0] == '-n':
        limit = int(args[1]); args = args[2:]
    files = sorted(glob.glob(os.path.join(SRC, '*.json.bin')))
    if args:
        files = [f for f in files if os.path.basename(f)[:-9] in args]
    out = open(OUT, 'w')
    total = 0
    for fn in files:
        buf = open(fn, 'rb').read()
        mn, n = unpack_from('<II', buf, 0)
        assert mn == 0xD33DBAE0, fn
        p = 8
        count = 0
        for k in range(n):
            full, ini, fin, tr, op, base = test(buf, p)
            p += full
            if limit is not None and k >= limit:
                continue
            if unpredictable(op, ini[31] & 0x20):
                continue
            data = [t for t in tr if t[0] != 0]
            words = [op, base] + list(ini) + list(fin) + [len(data)]
            for t in data:
                words += [t[0], t[1], t[2], t[3]]
            out.write(' '.join('%x' % w for w in words) + '\n')
            count += 1
        out.write('fffffffe\n')                  # (the file's end: the bench counts per file)
        print('%-40s %6d tests' % (os.path.basename(fn)[:-9], count))
        total += count
    out.write('ffffffff\n')
    out.close()
    print('%d tests -> %s' % (total, OUT))


if __name__ == '__main__':
    main()
