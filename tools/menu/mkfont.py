"""mkfont.py - the graphical menu's text: Nunito (tools/menu/fonts, SIL OFL 1.1) rendered at the
sizes and weights the menu uses into esp32/console/gfx_font.h -- anti-aliased, 4 bits of
coverage a pixel, Latin-1 (32-126, 160-255: "Pokemon" with its accent).

    python tools/menu/mkfont.py            -> esp32/console/gfx_font.h

Each font: a line height, an ascent, and per glyph its advance, its box (w x h, offset from the
pen at the baseline) and where its pixels start in one byte array (two pixels a byte, the
left one in the low nibble, rows padded to whole bytes).
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TTF = os.path.join(ROOT, 'tools', 'menu', 'fonts', 'Nunito.ttf')
OUT = os.path.join(ROOT, 'esp32', 'console', 'gfx_font.h')

# (name, size in pixels, weight): what the screens use
FONTS = [('F12', 12, 600), ('F12B', 12, 800), ('F14', 14, 600), ('F14B', 14, 800), ('F18', 18, 600),
         ('F18B', 18, 800), ('F22B', 22, 800), ('F24B', 24, 800), ('F30', 30, 700)]
CHARS = list(range(32, 127)) + list(range(160, 256))


def load(size, weight):
    f = ImageFont.truetype(TTF, size)
    f.set_variation_by_axes([weight])
    return f


def render(f, ch):
    """the glyph's coverage, cropped: (w, h, x offset, y offset from the baseline, advance, rows)"""
    asc, _ = f.getmetrics()
    s = chr(ch)
    adv = int(round(f.getlength(s)))
    pad = f.size
    img = Image.new('L', (adv + 2 * pad, asc + 2 * pad), 0)
    ImageDraw.Draw(img).text((pad, pad), s, font=f, fill=255)
    box = img.getbbox()
    if not box:
        return 0, 0, 0, 0, adv, []
    x0, y0, x1, y1 = box
    rows = [[img.getpixel((x, y)) for x in range(x0, x1)] for y in range(y0, y1)]
    return x1 - x0, y1 - y0, x0 - pad, y0 - pad - asc, adv, rows


def main():
    out = ['// gfx_font.h - GENERATED by tools/menu/mkfont.py from Nunito (SIL Open Font License 1.1,',
           '// tools/menu/fonts/OFL.txt). Do not edit: run the tool.', '#pragma once', '#include <stdint.h>', '',
           'namespace gfxfont {',
           'struct Glyph { uint32_t at; uint8_t w, h; int8_t dx, dy; uint8_t adv; };',
           'struct Font { uint8_t line, ascent; const Glyph *g; const uint8_t *px; };   // g: chars 32-126 then 160-255', '']
    total = 0
    for name, size, weight in FONTS:
        f = load(size, weight)
        asc, desc = f.getmetrics()
        glyphs, data = [], bytearray()
        for ch in CHARS:
            w, h, dx, dy, adv, rows = render(f, ch)
            glyphs.append((len(data), w, h, dx, dy, adv))
            for r in rows:
                q = [min(15, (v + 8) // 17) for v in r]
                if len(q) % 2:
                    q.append(0)
                for i in range(0, len(q), 2):
                    data.append(q[i] | (q[i + 1] << 4))
        total += len(data) + 8 * len(glyphs)
        out.append('static const uint8_t %s_px[%d] = {' % (name, len(data)))
        for i in range(0, len(data), 32):
            out.append('  ' + ','.join(str(b) for b in data[i:i + 32]) + ',')
        out.append('};')
        out.append('static const Glyph %s_g[%d] = {' % (name, len(glyphs)))
        for i in range(0, len(glyphs), 6):
            out.append('  ' + ' '.join('{%d,%d,%d,%d,%d,%d},' % g for g in glyphs[i:i + 6]))
        out.append('};')
        out.append('static const Font %s = { %d, %d, %s_g, %s_px };' % (name, asc + desc, asc, name, name))
        out.append('')
    out.append('}  // namespace gfxfont')
    open(OUT, 'w', newline='\n').write('\n'.join(out) + '\n')
    print('%s: %d fonts, %d kB' % (OUT, len(FONTS), total // 1024))


if __name__ == '__main__':
    sys.exit(main())
