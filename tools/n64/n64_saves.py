def eeprom_size(header):
    """512 (4 kbit), 2048 (16 kbit) or 0, for a cartridge header (z64 byte order)"""
    gid = header[0x3B:0x3E].decode('latin-1')
    region, revision = chr(header[0x3E]), header[0x3F]
    if gid == 'NK4':                          # Kirby 64: SRAM in early Japanese carts
        return 0 if region == 'J' and revision < 2 else 2048
    if gid == 'NDK':                          # Dark Rift: only the Japanese release
        return 512 if region == 'J' else 0
    if gid == 'NWT':                          # Wetrix: only the Japanese release
        return 512 if region == 'J' else 0
    if gid == 'NWR':                          # Wave Race 64
        return 512
    if gid == 'NSM':                          # Super Mario 64
        return 512
    if gid in ('ND3', 'ND4'):                 # Castlevania: only the Japanese releases
        return 2048 if region == 'J' else 0
    # libdragon and EverDrive homebrew say it in the header's last byte
    if gid[1:] == 'ED':
        return {1: 512, 2: 2048}.get(revision >> 4, 0)
    return EEPROM.get(gid, 0)
