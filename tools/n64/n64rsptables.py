"""The RSP's reciprocal and inverse-square-root tables (512 entries of 16 bits
each), from the formulas in tools/n64/n64rsp.py (ares's, ISC), as a Verilog ROM:
rtl/n64_rsp_tables.v. A case table rather than a hex file, so synthesis and
simulation need no file paths; with its registered output it becomes block RAM.

    python tools/n64/n64rsptables.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

TAB = chr(9)


class _Bus:
    dmem = bytearray(4096)
    imem = bytearray(4096)


def main():
    import n64rsp
    r = n64rsp.RSP(_Bus())
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'rtl', 'n64_rsp_tables.v')
    L = ['// n64_rsp_tables.v - generated by tools/n64/n64rsptables.py: do not edit.',
         "// The RSP's reciprocal (VRCP) and inverse square root (VRSQ) tables.",
         '`default_nettype none',
         'module n64_rsp_tables (',
         TAB + 'input  wire        clk,',
         TAB + 'input  wire [8:0]  a,',
         TAB + 'output reg  [15:0] recip,',
         TAB + 'output reg  [15:0] rsqrt',
         ');',
         TAB + 'always @(posedge clk) begin',
         TAB * 2 + 'case (a)']
    for i in range(512):
        L.append(TAB * 2 + "9'd%d: begin recip <= 16'h%04x; rsqrt <= 16'h%04x; end" % (i, r.recip[i], r.rsqrt[i]))
    L += [TAB * 2 + 'endcase', TAB + 'end', 'endmodule', '`default_nettype wire', '']
    with open(out, 'w', newline='') as f:
        f.write(chr(10).join(L))
    print(out)


if __name__ == '__main__':
    main()
