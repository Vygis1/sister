"""Writes rtl/n64_rdp_blut.v: the RDP blender's divider (tools/n64rdp.py BLENDER_LUT,
from parallel-RDP's luts.hpp, MIT) as a ROM, a clock from address to data.

    python tools/n64rdptables.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import n64rdp  # noqa: E402

L = n64rdp.BLENDER_LUT
out = ['// n64_rdp_blut.v - generated by tools/n64rdptables.py: do not edit.',
       '// The RDP blender\'s divider, [(sum << 11) | (blended >> 2)], as parallel-RDP has it',
       '// (luts.hpp blender_lut, MIT, copyright Hans-Kristian Arntzen).',
       '`default_nettype none',
       'module n64_rdp_blut (',
       '\tinput  wire        clk,',
       '\tinput  wire        ce,               // (q holds while low: the pipeline is stalled)',
       '\tinput  wire [14:0] a,',
       '\toutput reg  [7:0]  q',
       ');',
       '\t(* rom_style = "block" *) reg [7:0] r;',
       '\talways @(posedge clk) if (ce) q <= r;',
       '\talways @(*) begin',
       '\t\tcase (a)']
for i, v in enumerate(L):
    if v:
        out.append("\t\t15'd%d: r = 8'h%02x;" % (i, v))
out += ["\t\tdefault: r = 8'h00;", '\t\tendcase', '\tend', 'endmodule', '`default_nettype wire', '']
dst = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', 'rtl', 'n64_rdp_blut.v')
open(dst, 'w').write('\n'.join(out))
print('%s: %d non-zero entries' % (dst, sum(1 for v in L if v)))
