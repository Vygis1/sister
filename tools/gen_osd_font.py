"""gen_osd_font.py - rtl/osd_font.v from Daniel Hepper's font8x8_basic (public
domain; from the public-domain IBM VGA fonts via Marcel Sondaar):
https://github.com/dhepper/font8x8 -- the header is fetched into build/.

A few of the control codes, empty in the font, get the menu's own glyphs:
0x10 a right-pointing triangle (the cursor), 0x1E / 0x1F up and down triangles,
0x01-0x06 a frame's corners and lines, 0x07 a block, 0x0F a diamond.

    curl -o build/font8x8_basic.h https://raw.githubusercontent.com/dhepper/font8x8/master/font8x8_basic.h
    python tools/gen_osd_font.py
"""
import re

src = open('build/font8x8_basic.h').read()
rows = re.findall(r'\{((?:\s*0x[0-9A-Fa-f]{2},?){8})\s*\}', src)
font = [[int(v, 16) for v in re.findall(r'0x([0-9A-Fa-f]{2})', r)] for r in rows]
assert len(font) == 128, len(font)
# (bit 0 of each byte is the leftmost pixel)
font[0x10] = [0x02, 0x06, 0x0E, 0x1E, 0x0E, 0x06, 0x02, 0x00]   # cursor: a triangle pointing right
# the frame: thin lines through the cell's middle (column 3, row 3), corners, a block, a diamond
font[0x01] = [0x00, 0x00, 0x00, 0xF8, 0x08, 0x08, 0x08, 0x08]   # top-left corner
font[0x02] = [0x00, 0x00, 0x00, 0x0F, 0x08, 0x08, 0x08, 0x08]   # top-right corner
font[0x03] = [0x08, 0x08, 0x08, 0xF8, 0x00, 0x00, 0x00, 0x00]   # bottom-left corner
font[0x04] = [0x08, 0x08, 0x08, 0x0F, 0x00, 0x00, 0x00, 0x00]   # bottom-right corner
font[0x05] = [0x00, 0x00, 0x00, 0xFF, 0x00, 0x00, 0x00, 0x00]   # horizontal line
font[0x06] = [0x08, 0x08, 0x08, 0x08, 0x08, 0x08, 0x08, 0x08]   # vertical line
font[0x07] = [0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF]   # a block
font[0x0F] = [0x08, 0x1C, 0x3E, 0x7F, 0x3E, 0x1C, 0x08, 0x00]   # a diamond
font[0x1E] = [0x00, 0x08, 0x1C, 0x3E, 0x7F, 0x00, 0x00, 0x00]   # up
font[0x1F] = [0x00, 0x00, 0x00, 0x7F, 0x3E, 0x1C, 0x08, 0x00]   # down

out = ['// GENERATED by tools/gen_osd_font.py from font8x8_basic (Daniel Hepper, public domain,',
       '// from the public-domain IBM VGA fonts). Do not edit; regenerate.',
       '// A glyph row: bit 0 is the leftmost pixel.',
       '`default_nettype none',
       'module osd_font (input wire clk, input wire [9:0] a, output reg [7:0] q);   // a = {char, row}',
       '\talways @(posedge clk) case (a)']
for c in range(128):
    for r in range(8):
        if font[c][r]:
            out.append("\t\t10'h%03X: q <= 8'h%02X;" % (c * 8 + r, font[c][r]))
out += ["\t\tdefault: q <= 8'h00;", '\tendcase', 'endmodule', '`default_nettype wire', '']
open('rtl/osd_font.v', 'w', newline='\n').write('\n'.join(out))
print('rtl/osd_font.v:', sum(1 for c in font for r in c if r), 'non-empty rows')
