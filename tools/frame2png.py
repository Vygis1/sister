"""Turn a tb_smb frame dump (hex palette indices) into a PNG.

    python tools/frame2png.py build/smb_a.txt build/smb_a.png

The testbench writes palette indices rather than colours so that it has no
opinion about which NES palette is "right"; the choice lives here instead.
"""
import sys, zlib, struct

PAL = [
    (0x62,0x62,0x62),(0x00,0x2C,0x7C),(0x11,0x15,0x9C),(0x36,0x03,0x9C),
    (0x55,0x00,0x7C),(0x67,0x00,0x44),(0x67,0x07,0x04),(0x55,0x1C,0x00),
    (0x36,0x32,0x00),(0x11,0x44,0x00),(0x00,0x4E,0x00),(0x00,0x4C,0x04),
    (0x00,0x40,0x44),(0x00,0x00,0x00),(0x00,0x00,0x00),(0x00,0x00,0x00),
    (0xAB,0xAB,0xAB),(0x12,0x60,0xCE),(0x36,0x42,0xF6),(0x6A,0x27,0xF6),
    (0x96,0x1A,0xCE),(0xAC,0x1A,0x87),(0xAC,0x28,0x2E),(0x96,0x45,0x00),
    (0x6A,0x62,0x00),(0x36,0x7A,0x00),(0x12,0x86,0x00),(0x00,0x84,0x2E),
    (0x00,0x76,0x87),(0x00,0x00,0x00),(0x00,0x00,0x00),(0x00,0x00,0x00),
    (0xFF,0xFF,0xFF),(0x5D,0xB3,0xFF),(0x88,0x92,0xFF),(0xC2,0x76,0xFF),
    (0xF3,0x66,0xFF),(0xFF,0x6A,0xC0),(0xFF,0x79,0x62),(0xF3,0x99,0x18),
    (0xC2,0xB8,0x00),(0x88,0xD2,0x00),(0x5D,0xDF,0x38),(0x45,0xDD,0x80),
    (0x45,0xCF,0xD2),(0x4E,0x4E,0x4E),(0x00,0x00,0x00),(0x00,0x00,0x00),
    (0xFF,0xFF,0xFF),(0xBE,0xE0,0xFF),(0xCF,0xD5,0xFF),(0xE6,0xCA,0xFF),
    (0xFA,0xC3,0xFF),(0xFF,0xC5,0xEA),(0xFF,0xCC,0xC2),(0xFA,0xDA,0x9E),
    (0xE6,0xE7,0x8C),(0xCF,0xF2,0x8E),(0xBE,0xF7,0xA6),(0xB3,0xF7,0xC9),
    (0xB3,0xF2,0xF2),(0xB8,0xB8,0xB8),(0x00,0x00,0x00),(0x00,0x00,0x00),
]

src, dst = sys.argv[1], sys.argv[2]
rows = [l.strip() for l in open(src) if l.strip()]
W, H = 256, len(rows)
raw = bytearray()
for r in rows:
    raw.append(0)                                   # PNG filter: none
    for i in range(0, len(r), 2):
        c = r[i:i+2]
        # xsim prints 'x' for an unknown bit. Those are real information -- they
        # mark pixels driven from state nothing ever initialised -- so they get a
        # colour that cannot be mistaken for one the NES can produce.
        if 'x' in c.lower():
            raw += bytes([255, 0, 255])
        else:
            raw += bytes(PAL[int(c, 16) & 0x3F])

def chunk(tag, data):
    return (struct.pack(">I", len(data)) + tag + data
            + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF))

png = (b"\x89PNG\r\n\x1a\n"
       + chunk(b"IHDR", struct.pack(">IIBBBBB", W, H, 8, 2, 0, 0, 0))
       + chunk(b"IDAT", zlib.compress(bytes(raw), 9))
       + chunk(b"IEND", b""))
open(dst, "wb").write(png)
print(f"{dst}: {W}x{H}")
